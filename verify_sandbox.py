"""Verify sandbox.py. Run next to it:  python3 verify_sandbox.py

GENERATED BY CLADE TO TEST SANDBOX

Builds a throwaway project dir in your home, runs each check inside the
sandbox, and prints a table plus a JSON block to paste back.
CONTROL checks run the same action UNsandboxed to prove the test can fail.
"""

import json
import os
import shutil
import subprocess
import sys
import tempfile
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

HOME = Path.home()
work = Path(tempfile.mkdtemp(prefix=".sbx-verify-", dir=HOME))
(work / ".git").mkdir()
os.chdir(work)
os.environ["SBX_CANARY"] = "leaked"

import sandbox  # noqa: E402  (PROJECT is resolved from cwd at import time)

results = []


def record(name, status, detail=""):
    results.append({"check": name, "status": status, "detail": str(detail).strip()[:300]})


def check(name, ok, detail=""):
    record(name, "PASS" if ok else "FAIL", detail)


class _Abort(Exception):
    pass


def sh(cmd, timeout=15):
    return sandbox.run(cmd, timeout=timeout)


def sh_ran(cmd, timeout=15):
    """Run in the sandbox and report whether the command line really executed.

    A check that expects a command to FAIL must not pass just because bwrap
    itself failed to start. The sentinel proves the shell inside ran.
    """
    r = sandbox.run(f"{cmd}\necho __sbx_ran__", timeout=timeout)
    ran = "__sbx_ran__" in r.stdout
    r.stdout = r.stdout.replace("__sbx_ran__\n", "")
    return r, ran


def host(cmd):
    return subprocess.run(cmd, shell=True, capture_output=True, text=True, cwd=work)


NET = "python3 -c \"import socket; socket.create_connection(('1.1.1.1', 53), 3)\""

try:
    if not sandbox.available():
        p = subprocess.run(
            ["bwrap", "--ro-bind", "/", "/", "--unshare-all", "true"],
            capture_output=True, text=True,
        ) if shutil.which("bwrap") else None
        record("bwrap usable", "FAIL", p.stderr if p else "bwrap not on PATH")
    else:
        record("bwrap usable", "PASS")

        # preflight: can the sandbox run a trivial command at all?
        pre = sh("echo sbxok")
        if "sbxok" not in pre.stdout:
            record("sandbox runs a command", "FAIL", pre.stderr or "no output")
            raise _Abort()
        record("sandbox runs a command", "PASS")

        # filesystem writes
        outside = HOME / ".sbx-outside-probe"
        host(f"touch {outside}")
        check("CONTROL: unsandboxed write outside project works", outside.exists())
        outside.unlink(missing_ok=True)
        r, ran = sh_ran(f"touch {outside}")
        check("write outside project blocked", ran and not outside.exists(),
              r.stderr if ran else "sandbox did not run: " + r.stderr)
        outside.unlink(missing_ok=True)

        r = sh("touch inside.txt")
        check("write inside project allowed", (work / "inside.txt").exists(), r.stderr)
        r, ran = sh_ran("touch .git/x")
        check(".git is read-only", ran and not (work / ".git" / "x").exists(),
              r.stderr if ran else "sandbox did not run: " + r.stderr)

        r = sh("echo hi > /tmp/sbx_probe && cat /tmp/sbx_probe")
        tmp_ok = r.stdout.strip() == "hi"
        check("/tmp writable inside sandbox", tmp_ok, r.stderr)
        check("/tmp is private (host /tmp untouched)", tmp_ok and not Path("/tmp/sbx_probe").exists())

        # network
        if host(NET).returncode == 0:
            record("CONTROL: host can reach network", "PASS")
            r, ran = sh_ran(NET)
            check("network blocked", ran and "Traceback" in r.stderr, r.stderr[-200:])
        else:
            record("CONTROL: host can reach network", "SKIP", "host offline, network test inconclusive")

        # environment
        check("CONTROL: host env contains canary", "SBX_CANARY" in host("env").stdout)
        r = sh("env")
        check("host env not inherited", "HOME=/tmp" in r.stdout and "SBX_CANARY" not in r.stdout, r.stdout[:200])

        # credentials hidden
        ssh = HOME / ".ssh"
        if ssh.is_dir() and any(ssh.iterdir()):
            record("CONTROL: host can see ~/.ssh entries", "PASS")
            r, ran = sh_ran(f"ls -A {ssh}")
            seen = r.stdout.split()
            check("~/.ssh hidden", ran and not seen,
                  f"{len(seen)} entries visible" if ran else "sandbox did not run: " + r.stderr)
        else:
            record("~/.ssh hidden", "SKIP", "no ~/.ssh with contents on host")

        # WSL interop: Windows programs would run outside the sandbox
        win = "/mnt/c/Windows/System32/cmd.exe"
        if Path(win).exists() and "sbxinterop" in host(f"{win} /c echo sbxinterop").stdout:
            record("CONTROL: host can run Windows programs", "PASS")
            r1, ran1 = sh_ran(f"{win} /c echo sbxinterop")
            r2, ran2 = sh_ran("powershell.exe -NoProfile -c echo sbxinterop")
            leaked = "sbxinterop" in r1.stdout or "sbxinterop" in r2.stdout
            check("Windows interop blocked", ran1 and ran2 and not leaked,
                  f"shell ran: {ran1 and ran2}, leaked: {leaked}")
        else:
            record("Windows interop blocked", "SKIP", "not WSL, or interop already off")

        # WSL interop sockets: the other route to Windows
        wsl = Path("/run/WSL")
        if wsl.is_dir() and any("interop" in p.name for p in wsl.iterdir()):
            record("CONTROL: host sees WSL interop sockets", "PASS")
            r, ran = sh_ran("ls -A /run/WSL")
            check("WSL interop sockets hidden", ran and "interop" not in r.stdout,
                  f"shell ran: {ran}, entries: {r.stdout.split() or 'none'}")
        else:
            record("WSL interop sockets hidden", "SKIP", "no /run/WSL interop sockets on host")

        # pid namespace
        r = sh("ls /proc | grep -c '^[0-9]'")
        n = int(r.stdout.strip() or 999)
        check("PID namespace isolated", n < 10, f"{n} pids visible")

        # controlling terminal
        if sys.stdin.isatty():
            r = sh("python3 -c \"print(open('/proc/self/stat').read().split(')')[-1].split()[4])\"")
            check("no controlling tty (--new-session)", r.stdout.strip() == "0", f"tty_nr={r.stdout.strip()}")
        else:
            record("no controlling tty (--new-session)", "SKIP", "run from an interactive terminal")

        # timeout kills the whole tree
        t = time.time()
        r = sh("sleep 31.337 & sleep 31.337", timeout=2)
        dt = time.time() - t
        time.sleep(0.5)
        left = subprocess.run(["pgrep", "-f", "sleep 31.337"], capture_output=True, text=True)
        check("timeout kills whole process tree",
              r.returncode == 124 and dt < 6 and left.returncode != 0,
              f"{dt:.1f}s, leftover pids: {left.stdout.strip() or 'none'}")

        # output cap
        r = sh("head -c 500000 /dev/zero | tr '\\0' x")
        check("output capped", len(r.stdout) == sandbox.MAX_OUTPUT, f"len={len(r.stdout)}")

        # informational probes: what is exposed (not pass/fail)
        probes = {
            "/mnt/c visible": "ls /mnt/c 2>&1 | head -3",
            "/mnt/c writable": "touch /mnt/c/sbx_probe_delete_me 2>&1 && echo WRITABLE",
            "PATH": "echo $PATH",
            "docker.sock visible": "ls -l /var/run/docker.sock 2>&1",
            "seccomp mode (0 = none)": "grep Seccomp: /proc/self/status",
        }
        for label, cmd in probes.items():
            r = sh(cmd)
            record("INFO " + label, "INFO", f"rc={r.returncode} {r.stdout.strip() or r.stderr.strip()}")
        host("rm -f /mnt/c/sbx_probe_delete_me")
except _Abort:
    pass
finally:
    os.chdir(HOME)
    shutil.rmtree(work, ignore_errors=True)

width = max(len(r["check"]) for r in results)
for r in results:
    print(f"[{r['status']:<4}] {r['check']:<{width}}  {r['detail'][:80]}")
print("\n----- paste everything below back into chat -----")
print(json.dumps(results, indent=1))
